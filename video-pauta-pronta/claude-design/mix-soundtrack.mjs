cues.forEach((c, i) => { const ms = Math.round(c.at * 1000);
  fc += `[${i + 1}]aformat=sample_rates=44100:channel_layouts=stereo${c.tempo ? `,atempo=${c.tempo}` : ''}${c.dur ? `,atrim=0:${c.dur},afade=t=out:st=${(c.dur - 0.12).toFixed(2)}:d=0.12` : ''},volume=${c.vol},adelay=${ms}|${ms}[c${i}];`; });
